export const STRINGS: Record<Lang, Record<Key, string>> = { en, es, de, fr, ja };

let lang: Lang = "en";
export const setLang = (next: Lang) => (lang = next);
export const getLang = () => lang;

/** A text in a given language (the PDF report has its own: the built-in PDF fonts cannot draw Japanese). */
export const tIn = (l: Lang, key: Key, vars: Record<string, string | number> = {}) =>
  STRINGS[l][key].replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? ""));
export const t = (key: Key, vars: Record<string, string | number> = {}) => tIn(lang, key, vars);
